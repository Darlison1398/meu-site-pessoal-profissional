let currentLang = localStorage.getItem('portfolio-lang') || 'pt-BR';
let typingController = null;

function t(key) {
  const keys = key.split('.');
  let value = translations[currentLang];
  for (const k of keys) {
    value = value?.[k];
  }
  return value ?? key;
}

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem('portfolio-lang', lang);
  document.documentElement.lang = lang;

  applyTranslations();
  updateLangToggle();
  updateMeta();
  restartTypingEffect();

  document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });

  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });

  document.querySelectorAll('[data-i18n-list]').forEach(ul => {
    const key = ul.dataset.i18nList;
    const items = t(key);
    if (!Array.isArray(items)) return;
    ul.innerHTML = items.map(item => `<li>${item}</li>`).join('');
  });

  document.querySelectorAll('[data-i18n-tags]').forEach(container => {
    const key = container.dataset.i18nTags;
    const tags = t(key);
    if (!Array.isArray(tags)) return;
    container.innerHTML = tags.map(tag => `<span class="tech-tag">${tag}</span>`).join('');
  });
}

function updateMeta() {
  document.title = t('meta.title');
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.content = t('meta.description');
}

function updateLangToggle() {
  document.querySelectorAll('[data-lang-btn]').forEach(btn => {
    const isActive = btn.dataset.langBtn === currentLang;
    btn.classList.toggle('lang-btn-active', isActive);
    btn.setAttribute('aria-pressed', isActive);
  });
}

function initI18n() {
  setLanguage(currentLang);

  document.querySelectorAll('[data-lang-btn]').forEach(btn => {
    btn.addEventListener('click', () => setLanguage(btn.dataset.langBtn));
  });
}

function getCurrentLang() {
  return currentLang;
}

function getTypedPhrases() {
  return t('hero.typedPhrases');
}

function restartTypingEffect() {
  if (typingController) typingController.restart();
}

function registerTypingController(controller) {
  typingController = controller;
}
